import {test} from 'node:test';
import assert from 'node:assert/strict';
import {Hono} from 'hono';
import {sprintStage} from '../../../../shared/spec-sprints.ts';
import type {ReconstructionMaterial,ReconstructionPlan} from '../../../../shared/spec-versioning.ts';
process.env.PRAEFORMA_LOCAL_MODE='1';
const counts=(over:Partial<Record<'total'|'implemented'|'unimplemented'|'unverified'|'reconstructed'|'pendingNotImplemented',number>>)=>({total:0,implemented:0,unimplemented:0,unverified:0,reconstructed:0,pendingNotImplemented:0,...over});
test('PF-SPRINT-4 derives the stage from fragment states',()=>{
  assert.equal(sprintStage(counts({})),'empty');
  assert.equal(sprintStage(counts({total:2,unimplemented:1,implemented:1,pendingNotImplemented:1})),'checking');
  assert.equal(sprintStage(counts({total:2,implemented:2})),'ready');
  assert.equal(sprintStage(counts({total:2,implemented:1,unimplemented:1,reconstructed:1})),'ready');
  assert.equal(sprintStage(counts({total:2,unimplemented:2,reconstructed:2})),'structured');
});
test('PF-SPRINT-1/2/3/5/7/8 group, check and structure fragments per sprint',async()=>{
  const {initLocalDb,getDb,getLocalSqlite}=await import('../../db/connection.ts');
  const {projects,projectMembers}=await import('../../db/schema/project.ts');
  const {domains}=await import('../../db/schema/domain.ts');
  const {enableLocalAuth}=await import('../../middleware/require-auth.ts');
  const {makeSpecFragmentRouter}=await import('../../routes/spec-fragments.ts');
  const {makeSpecVersionRouter}=await import('../../routes/spec-versions.ts');
  const {makeSpecSprintRouter}=await import('../../routes/spec-sprints.ts');
  const {AppError}=await import('../errors.ts');
  const state=await initLocalDb(':memory:');assert.equal(state.ok,true,state.error??undefined);
  const sqlite=getLocalSqlite() as unknown as {close():void};
  try{
    const identify=(userId:string)=>enableLocalAuth({userId,displayName:null,role:'user',projectKey:null});identify('author');
    await getDb().insert(projects).values([{id:'p',name:'One',orgId:'test',ownerUserId:'author'},{id:'q',name:'Two',orgId:'test',ownerUserId:'author'}]);
    await getDb().insert(projectMembers).values([{id:'a',projectId:'p',userId:'author',role:'owner'},{id:'b',projectId:'q',userId:'author',role:'owner'},{id:'c',projectId:'p',userId:'reader',role:'viewer'}]);
    await getDb().insert(domains).values({id:'d',projectId:'p',name:'Town'});
    const seen:{material:ReconstructionMaterial|null}={material:null};
    const app=new Hono();app.onError(e=>new Response(JSON.stringify({error:e.message}),{status:e instanceof AppError?e.status:500}));
    app.route('/projects/:pid/spec-fragments',makeSpecFragmentRouter());
    app.route('/projects/:pid/spec-sprints',makeSpecSprintRouter());
    app.route('/projects/:pid/spec-versions',makeSpecVersionRouter('unused',async(_binary,material):Promise<ReconstructionPlan>=>{seen.material=material;
      return {changes:[{specId:null,domainId:'d',title:'Town',description:material.fragments.map(f=>f.content).join('\n'),fragmentIds:material.fragments.map(f=>f.id),rationale:'Sprint'}],deferred:[]};}));
    const send=(method:string,path:string,body?:unknown)=>app.request(path,{method,...(body?{headers:{'content-type':'application/json'},body:JSON.stringify(body)}:{})});
    const fragment=async(pid:string,content:string,n:number)=>((await (await send('POST',`/projects/${pid}/spec-fragments`,{content,sourceEventId:`00000000-0000-4000-8000-00000000000${n}`})).json()) as {fragment:{id:string;revision:number}}).fragment;
    const signs=await fragment('p','Signs stand beside the road',1);
    const mouse=await fragment('p','Mouse click on PC',2);
    const loose=await fragment('p','Gamepad support',3);
    const other=await fragment('q','Other project',4);
    let response=await send('POST','/projects/p/spec-sprints',{title:'Town feel',goal:'Readable town',fragmentIds:[signs.id,mouse.id]});
    assert.equal(response.status,201);
    const sprint=(await response.json() as {sprint:{id:string;stage:string;counts:{total:number}}}).sprint;
    assert.equal(sprint.stage,'checking');assert.equal(sprint.counts.total,2);
    assert.equal((await send('POST','/projects/p/spec-sprints',{title:'Dup',fragmentIds:[signs.id]})).status,409);
    assert.equal((await send('POST','/projects/p/spec-sprints',{title:'Cross',fragmentIds:[other.id]})).status,404);
    assert.equal((await send('POST',`/projects/p/spec-sprints/${sprint.id}/fragments`,{fragmentIds:[signs.id]})).status,200);
    const unassigned=await (await send('GET','/projects/p/spec-sprints/unassigned')).json() as {items:Array<{id:string}>};
    assert.deepEqual(unassigned.items.map(f=>f.id),[loose.id]);
    for(const f of [signs,mouse])assert.equal((await send('PATCH',`/projects/p/spec-fragments/${f.id}/implementation`,{expectedRevision:f.revision,implementationState:'implemented',implementationEvidence:'played'})).status,200);
    let detail=await (await send('GET',`/projects/p/spec-sprints/${sprint.id}`)).json() as {sprint:{stage:string};fragments:Array<{id:string;reconstructed:boolean}>};
    assert.equal(detail.sprint.stage,'ready');assert.equal(detail.fragments.length,2);
    identify('reader');
    assert.equal((await send('POST','/projects/p/spec-sprints',{title:'No'})).status,403);
    assert.equal((await send('GET',`/projects/p/spec-sprints/${sprint.id}`)).status,200);
    identify('author');
    assert.equal((await send('GET',`/projects/q/spec-sprints/${sprint.id}`)).status,404);
    assert.equal((await send('POST','/projects/q/spec-versions/reconstructions',{sprintId:sprint.id})).status,404);
    response=await send('POST','/projects/p/spec-versions/reconstructions',{sprintId:sprint.id});assert.equal(response.status,201);
    assert.deepEqual(seen.material!.fragments.map(f=>f.id).sort(),[signs.id,mouse.id].sort());assert.equal(seen.material!.sprintId,sprint.id);
    const proposal=(await response.json() as {proposal:{id:string}}).proposal;
    assert.equal((await send('POST',`/projects/p/spec-versions/reconstructions/${proposal.id}/confirm`)).status,200);
    detail=await (await send('GET',`/projects/p/spec-sprints/${sprint.id}`)).json() as typeof detail;
    assert.equal(detail.sprint.stage,'structured');assert.ok(detail.fragments.every(f=>f.reconstructed));
    assert.equal((await send('DELETE',`/projects/p/spec-sprints/${sprint.id}/fragments/${signs.id}`)).status,409);
    const second=(await (await send('POST','/projects/p/spec-sprints',{title:'Input',fragmentIds:[loose.id]})).json() as {sprint:{id:string}}).sprint;
    assert.equal((await send('DELETE',`/projects/p/spec-sprints/${second.id}/fragments/${loose.id}`)).status,200);
    assert.equal((await send('DELETE',`/projects/p/spec-sprints/${second.id}/fragments/${loose.id}`)).status,404);
    assert.equal((await send('POST','/projects/p/spec-versions/reconstructions',{sprintId:second.id})).status,400);
    response=await send('POST','/projects/p/spec-versions/reconstructions');assert.equal(response.status,201);
    assert.deepEqual(seen.material!.fragments.map(f=>f.id),[loose.id]);assert.equal(seen.material!.sprintId,undefined);
    const list=await (await send('GET','/projects/p/spec-sprints')).json() as {items:Array<{id:string}>;canEdit:boolean;canReconstruct:boolean};
    assert.deepEqual(list.items.map(s=>s.id).sort(),[second.id,sprint.id].sort());assert.equal(list.canReconstruct,true);
  }finally{sqlite.close();}
});
