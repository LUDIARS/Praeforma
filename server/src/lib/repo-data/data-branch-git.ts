/** Writes files to a dedicated branch without touching the repository's working tree. */
import { execFile } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { AppError } from '../errors.ts';

export const DATA_BRANCH = 'pf-data';
export const DATA_MANIFEST_PATH = 'pf-data.json';
const DATA_REF = `refs/heads/${DATA_BRANCH}`;
const NO_COMMIT = '0000000000000000000000000000000000000000';
const GIT_TIMEOUT_MS = 30_000;
const GIT_PUSH_TIMEOUT_MS = 120_000;
const GIT_MAX_OUTPUT_BYTES = 64 * 1024 * 1024;
const COMMITTER = { GIT_AUTHOR_NAME: 'Praeforma', GIT_AUTHOR_EMAIL: 'praeforma@ludiars.invalid',
  GIT_COMMITTER_NAME: 'Praeforma', GIT_COMMITTER_EMAIL: 'praeforma@ludiars.invalid' };

export interface DataFile { path: string; content: string }
export interface PublishResult { branch: string; commit: string; changed: boolean; files: number }

interface GitOptions { input?: string; env?: NodeJS.ProcessEnv; allowFailure?: boolean; timeoutMs?: number }

function git(repoDir: string, args: string[], options: GitOptions = {}): Promise<string | null> {
  return new Promise((resolve, reject) => {
    const child = execFile('git', ['-C', repoDir, ...args], {
      encoding: 'utf8', windowsHide: true, timeout: options.timeoutMs ?? GIT_TIMEOUT_MS, maxBuffer: GIT_MAX_OUTPUT_BYTES,
      env: { ...process.env, ...options.env },
    }, (error, stdout) => {
      if (!error) return resolve(stdout.trim());
      if (options.allowFailure) return resolve(null);
      reject(AppError.internal(`git_failed:${args[0]}`));
    });
    child.stdin?.end(options.input ?? '');
  });
}

async function previousGeneratedPaths(repoDir: string, head: string | null): Promise<string[]> {
  if (!head) return [];
  const text = await git(repoDir, ['show', `${head}:${DATA_MANIFEST_PATH}`], { allowFailure: true });
  if (text === null) return [];
  const manifest = JSON.parse(text) as { files?: unknown };
  return Array.isArray(manifest.files) ? manifest.files.filter((file): file is string => typeof file === 'string') : [];
}

/**
 * Replaces the files generated by the previous publish with `files`, keeping
 * anything people added to the branch by hand. No commit is made when nothing
 * changed. `files` must contain the manifest listing their paths.
 */
export async function publishToDataBranch(repoDir: string, files: readonly DataFile[], message: string): Promise<PublishResult> {
  const head = await git(repoDir, ['rev-parse', '-q', '--verify', DATA_REF], { allowFailure: true });
  const indexDir = await mkdtemp(join(tmpdir(), 'pf-data-index-'));
  try {
    const env = { GIT_INDEX_FILE: join(indexDir, 'index') };
    if (head) await git(repoDir, ['read-tree', head], { env });

    const written = new Set(files.map((file) => file.path));
    for (const path of await previousGeneratedPaths(repoDir, head)) {
      if (!written.has(path)) await git(repoDir, ['update-index', '--force-remove', '--', path], { env });
    }
    for (const file of files) {
      const blob = (await git(repoDir, ['hash-object', '-w', '--stdin'], { input: file.content }))!;
      await git(repoDir, ['update-index', '--add', '--cacheinfo', `100644,${blob},${file.path}`], { env });
    }

    const tree = (await git(repoDir, ['write-tree'], { env }))!;
    if (head && (await git(repoDir, ['rev-parse', `${head}^{tree}`])) === tree) {
      return { branch: DATA_BRANCH, commit: head, changed: false, files: files.length };
    }
    const parent = head ? ['-p', head] : [];
    const commit = (await git(repoDir, ['commit-tree', tree, ...parent, '-m', message], { env: COMMITTER }))!;
    const moved = await git(repoDir, ['update-ref', DATA_REF, commit, head ?? NO_COMMIT], { allowFailure: true });
    if (moved === null) throw AppError.conflict('data_branch_moved');
    return { branch: DATA_BRANCH, commit, changed: true, files: files.length };
  } finally {
    await rm(indexDir, { recursive: true, force: true });
  }
}

export function readDataBranchHead(repoDir: string): Promise<string | null> {
  return git(repoDir, ['rev-parse', '-q', '--verify', DATA_REF], { allowFailure: true });
}

/** Null when the branch or the file does not exist. */
export function readDataBranchFile(repoDir: string, path: string): Promise<string | null> {
  return git(repoDir, ['show', `${DATA_REF}:${path}`], { allowFailure: true });
}

/** Sends only the data branch to the repository's configured origin. */
export async function pushDataBranch(repoDir: string): Promise<string> {
  const head = await readDataBranchHead(repoDir);
  if (!head) throw AppError.conflict('data_branch_missing');
  const pushed = await git(repoDir, ['push', 'origin', `${DATA_REF}:${DATA_REF}`], { allowFailure: true, timeoutMs: GIT_PUSH_TIMEOUT_MS });
  if (pushed === null) throw AppError.conflict('data_branch_push_failed');
  return head;
}
